using System.Collections.Generic;
using System.IO;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

namespace ShiftShift.EditorTools
{
    /// <summary>
    /// Playbook 2.5, run by Shift+Shift > Set Up Visuals: fills the Menu scene (input + MainMenu with the six levels
    /// in play order), and makes sure Boot, Menu, Run and Calibrate lead the build list. Boot opens the menu and the
    /// calibration screen returns to it (set in those scenes' files).
    /// </summary>
    public static partial class GreyboxSetup
    {
        private const string MenuScenePath = "Assets/_Game/Scenes/Menu.unity";

        private const string CreditsText =
            "SHIFT+SHIFT\n" +
            "Made for GitHub Game Off 2026. Theme: SHIFT.\n\n" +
            "Design, code, levels and testing: ELIA\n" +
            "Engine: Unity 6 (URP)\n" +
            "Sound: placeholder clicks generated by the project\n\n" +
            "Thank you for playing.";

        private static void WireMenuScene(List<string> log)
        {
            if (!File.Exists(MenuScenePath)) return;
            var scene = EditorSceneManager.OpenScene(MenuScenePath, OpenSceneMode.Single);

            var input = Object.FindAnyObjectByType<ShiftInput>();
            if (input == null) input = new GameObject("Input").AddComponent<ShiftInput>();
            Set(input, "settings", AssetDatabase.LoadAssetAtPath<GestureSettings>(SettingsPath)); // after the scene is open

            var menu = Object.FindAnyObjectByType<MainMenu>();
            bool created = menu == null;
            if (created) menu = new GameObject("Menu").AddComponent<MainMenu>();
            Set(menu, "input", input);

            var so = new SerializedObject(menu);
            SerializedProperty levels = so.FindProperty("levels");
            var found = new List<TextAsset>();
            for (int n = 1; n <= 6; n++)
            {
                var json = AssetDatabase.LoadAssetAtPath<TextAsset>($"Assets/_Game/Levels/level{n:00}.json");
                if (json != null) found.Add(json);
            }
            levels.arraySize = found.Count;
            for (int i = 0; i < found.Count; i++) levels.GetArrayElementAtIndex(i).objectReferenceValue = found[i];
            if (created) so.FindProperty("credits").stringValue = CreditsText; // later edits in the Inspector are kept
            so.ApplyModifiedPropertiesWithoutUndo();

            Camera cam = Camera.main;
            if (cam != null)
            {
                cam.clearFlags = CameraClearFlags.SolidColor;
                cam.backgroundColor = Hex("#101418");
            }
            EditorSceneManager.MarkSceneDirty(scene);
            EditorSceneManager.SaveScene(scene);

            // Build list: Boot, Menu, Run, Calibrate first, then whatever else was listed.
            string[] wanted = { BootScenePath, MenuScenePath, RunScenePath, CalibrateScenePath };
            var list = new List<EditorBuildSettingsScene>();
            foreach (string p in wanted)
                if (File.Exists(p)) list.Add(new EditorBuildSettingsScene(p, true));
            foreach (EditorBuildSettingsScene s in EditorBuildSettings.scenes)
                if (System.Array.IndexOf(wanted, s.path) < 0) list.Add(s);
            EditorBuildSettings.scenes = list.ToArray();

            log.Add($"Menu: {found.Count} levels, calibrate, credits; build list starts Boot, Menu, Run, Calibrate");
        }
    }
}
